export function scriptSettingCompletenessGuidance(stage: ScriptStage): string {
  return `${scriptCreativeAuthorityGuidance}\n【本阶段交付前设定核对】\n` +
    scriptStageSettingCriteria[stage].map(item => `- ${item}`).join('\n') + '\n' +
    '提交草稿前按上述要求进行语义核对，发现授权范围内的缺失、占位或矛盾就补齐并重新检查。同一方案的决定应同步到本阶段各文档和分场；不能只删除“待定”等字样而不确定内容。补齐历史缺失栏目时，仍须原样保留已有标题和正文，历史问题只明确列出，不借完整性核对扩大修改范围。不得将内部检查清单或自评分数写入正文；草稿供创作者预览，确认后才保存。\n'
}
