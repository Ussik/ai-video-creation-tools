已确认事实、创作者明确要求自行决定或暂缓的事项、明确禁止的内容及本轮范围必须保持。普通讨论不授权生成文档；决定某一设定不授权跳阶段、改其他文档或保存。创作者已委托决定的事项后续沿用，除非创作者修改；继续已授权任务不重复确认相同授权。
