export function scriptStageQualityGuidance(stage: ScriptStage): string {
  return `创作质量要求：\n${stageQualityCriteria[stage].map(criterion => `- ${criterion}`).join('\n')}\n` +
    '生成前检查本阶段的因果、人物行为、情绪节奏、铺垫兑现与关联资料一致性；在授权范围内改进草稿，保留已确认事实。不把检查清单或自评分数当作文档正文，不宣称作品质量已获保证。\n'
}

